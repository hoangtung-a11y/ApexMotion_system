// Hàm sinh vector đặc trưng 16 chiều (đại diện cho vector 1536 chiều của pgvector) dựa trên ngữ nghĩa tiếng Việt
export function computeSemanticVector(text: string): number[] {
  const normalized = text.toLowerCase()
  const dimensions = [
    // 0: Giày chạy bộ / marathon
    /giày|chạy|marathon|sneaker|slip-on|taichi|nitro|velocity|bước chạy/.test(normalized) ? 0.95 : 0.05,
    // 1: Cầu lông / vợt
    /vợt|cầu lông|yonex|astrox|đập cầu|3u|4u/.test(normalized) ? 0.95 : 0.05,
    // 2: Quần áo / trang phục tập gym
    /áo|quần|trang phục|đồ tập|gym|dry-fit|compression|thấm mồ hôi/.test(normalized) ? 0.95 : 0.05,
    // 3: Dụng cụ / thảm yoga / phụ kiện
    /thảm|yoga|dụng cụ|pilates|tpe|tập tại nhà|phụ kiện/.test(normalized) ? 0.95 : 0.05,
    // 4: Phân khúc giá rẻ (< 500k)
    /250|350|420|500|giá rẻ|sinh viên|dưới 500/.test(normalized) ? 0.85 : 0.15,
    // 5: Phân khúc tầm trung (< 1 triệu - 2 triệu)
    /999|1650|1\.650|dưới 2 triệu|< 2tr|2tr|1 triệu/.test(normalized) ? 0.9 : 0.1,
    // 6: Size giày 41-43
    /size 41|size 42|size 43|\b42\b|\b41\b|\b43\b/.test(normalized) ? 0.9 : 0.1,
    // 7: Size giày 39-40
    /size 39|size 40|\b39\b|\b40\b/.test(normalized) ? 0.9 : 0.1,
    // 8: Size áo M/L/XL
    /size m|size l|size xl|\bm\b|\bl\b|\bxl\b/.test(normalized) ? 0.85 : 0.1,
    // 9: Ưu đãi hot / bán chạy
    /ưu đãi|hot|khuyến mãi|bán chạy|tốt nhất|nổi bật/.test(normalized) ? 0.85 : 0.2,
  ]
  const norm = Math.sqrt(dimensions.reduce((acc, v) => acc + v * v, 0)) || 1
  return dimensions.map((v) => Number((v / norm).toFixed(4)))
}

